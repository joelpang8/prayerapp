/**
 * Regenerates src/lib/scripture/rv1909/*.json from eBible.org's Reina-Valera
 * 1909 (Spanish, public domain / "Dominio Público"):
 *
 *   curl -LO https://ebible.org/Scriptures/spaRV1909_vpl.zip   # unzip it
 *   npx tsx scripts/generate-rv1909.ts path/to/spaRV1909_vpl.txt
 *
 * Output: one file per book, [chapter][verse] -> text, like the KJV. Words in
 * [brackets] were added by the translators (printed in italics); the app
 * renders them in italics. eBible's book codes differ for a few books (SOL,
 * EZE, JOE, MAR, JOH, PHI, JAM, 1JO…), so books are matched by order, and
 * each book's versification must equal the KJV table in books.ts.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BOOKS } from "../src/lib/scripture/books";

const file = process.argv[2];
if (!file) throw new Error("Usage: npx tsx scripts/generate-rv1909.ts path/to/spaRV1909_vpl.txt");

// Lines look like: GEN 1:1 EN el principio crió Dios los cielos y la tierra.
const LINE = /^([1-3]?[A-Z]{2,3}) (\d+):(\d+) (.*)$/;
const byBook = new Map<string, string[][]>();
const order: string[] = [];
for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
  if (!line.trim()) continue;
  const m = LINE.exec(line);
  if (!m) throw new Error(`Unexpected line: ${line.slice(0, 80)}`);
  const [, code, ch, v, text] = m;
  if (!byBook.has(code)) {
    byBook.set(code, []);
    order.push(code);
  }
  const chapters = byBook.get(code)!;
  const c = Number(ch) - 1;
  chapters[c] ??= [];
  if (chapters[c].length !== Number(v) - 1) throw new Error(`Out of order: ${code} ${ch}:${v}`);
  chapters[c].push(text.replace(/\s+/g, " ").trim());
}

// A few chapters are numbered differently in Spanish Bibles (e.g. KJV
// Jonah 1:17 is RV Jonah 2:1). eBible keeps the KJV slots but leaves the
// moved verses empty and shifts the next chapter, so references there would
// show the wrong words. Those chapters are listed, and the app shows the KJV
// for them instead (labelled KJV): the chapter with empty verses, and the
// next one when the empties are at its end.
const differs: Record<string, number[]> = {};

if (order.length !== BOOKS.length) throw new Error(`Expected ${BOOKS.length} books, got ${order.length}`);
const outDir = join(import.meta.dirname, "..", "src", "lib", "scripture", "rv1909");
let verses = 0;
BOOKS.forEach((book, i) => {
  const chapters = byBook.get(order[i])!;
  const shape = chapters.map((c) => c.length);
  if (JSON.stringify(shape) !== JSON.stringify(book.verses)) {
    throw new Error(`${book.id} (${order[i]}): versification differs from books.ts`);
  }
  verses += shape.reduce((a, b) => a + b, 0);
  chapters.forEach((c, ci) => {
    const empty = c.map((v, vi) => (v ? -1 : vi)).filter((vi) => vi >= 0);
    if (empty.length === 0) return;
    const list = (differs[book.id] ??= []);
    if (!list.includes(ci + 1)) list.push(ci + 1);
    if (empty.at(-1) === c.length - 1 && ci + 1 < chapters.length && !list.includes(ci + 2)) list.push(ci + 2);
  });
  writeFileSync(join(outDir, `${book.id}.json`), JSON.stringify(chapters));
});
const loaders = BOOKS.map((b) => `  ${JSON.stringify(b.id)}: () => import("./${b.id}.json"),`).join("\n");
writeFileSync(
  join(outDir, "index.ts"),
  `// GENERATED by scripts/generate-rv1909.ts. Do not edit.\n` +
    `type Chapters = string[][];\n` +
    `export const RV1909_BOOKS: Record<string, () => Promise<{ default: Chapters }>> = {\n${loaders}\n};\n` +
    `/** Chapters numbered differently from the KJV: the app shows the KJV there. */\n` +
    `export const RV1909_NUMBERED_DIFFERENTLY: Record<string, readonly number[]> = ${JSON.stringify(differs)};\n`,
);
console.log(`Wrote ${BOOKS.length} books, ${verses} verses to ${outDir}`);
