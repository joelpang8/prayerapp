/**
 * Regenerates the bundled modern English Bibles from eBible.org (both public
 * domain):
 *
 *   BSB  Berean Standard Bible   curl -LO https://ebible.org/Scriptures/engbsb_vpl.zip
 *   WEB  World English Bible     curl -LO https://ebible.org/Scriptures/engwebp_vpl.zip
 *                                (engwebp: the Protestant canon, 66 books)
 *
 *   unzip each, then:
 *   npx tsx scripts/generate-english.ts BSB path/to/engbsb_vpl.txt
 *   npx tsx scripts/generate-english.ts WEB path/to/engwebp_vpl.txt
 *
 * Output: src/lib/scripture/<bsb|web>/, one file per book, [chapter][verse]
 * -> text, laid out on the KJV's numbering (which stored references use):
 *  - Verses these translations leave out (e.g. Matthew 17:21, kept only in a
 *    footnote) are empty strings; the app skips them, as printed Bibles do.
 *  - The WEB prints Romans 16:25-27 at the end of Romans 14 (as 14:24-26);
 *    they're put back at 16:25-27 so a reference finds them.
 * Anything else that differs from the KJV table in books.ts is an error.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { BOOKS } from "../src/lib/scripture/books";

const [id, file] = process.argv.slice(2);
if ((id !== "BSB" && id !== "WEB") || !file) throw new Error("Usage: npx tsx scripts/generate-english.ts BSB|WEB path/to/<name>_vpl.txt");

// Lines look like: GEN 1:1 In the beginning God created the heavens and the earth.
const LINE = /^([1-3]?[A-Z]{2,3}) (\d+):(\d+) ?(.*)$/;
const byBook = new Map<string, Map<number, Map<number, string>>>();
const order: string[] = [];
for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
  if (!line.trim()) continue;
  const m = LINE.exec(line);
  if (!m) throw new Error(`Unexpected line: ${line.slice(0, 80)}`);
  const [, code, ch, v, text] = m;
  if (!byBook.has(code)) {
    byBook.set(code, new Map());
    order.push(code);
  }
  const chapters = byBook.get(code)!;
  if (!chapters.has(Number(ch))) chapters.set(Number(ch), new Map());
  chapters.get(Number(ch))!.set(Number(v), text.replace(/\s+/g, " ").trim());
}
if (order.length !== BOOKS.length) throw new Error(`Expected ${BOOKS.length} books, got ${order.length}`);

/** [book, from chapter:first..last] -> [to chapter:first]: verses printed elsewhere than in the KJV. */
const MOVED: Record<string, { book: string; from: [number, number, number]; to: [number, number] }[]> = {
  BSB: [],
  WEB: [{ book: "ROM", from: [14, 24, 26], to: [16, 25] }],
};

const outDir = join(import.meta.dirname, "..", "src", "lib", "scripture", id.toLowerCase());
mkdirSync(outDir, { recursive: true });
let verses = 0;
const omitted: string[] = [];
BOOKS.forEach((book, i) => {
  const source = byBook.get(order[i])!;
  if (source.size !== book.verses.length) throw new Error(`${book.id}: ${source.size} chapters, KJV has ${book.verses.length}`);
  const moved = MOVED[id].filter((m) => m.book === book.id);
  const chapters = book.verses.map((count, ci) => {
    const src = source.get(ci + 1);
    if (!src) throw new Error(`${book.id} ${ci + 1} missing`);
    const out: string[] = [];
    for (let v = 1; v <= count; v++) out.push(src.get(v) ?? "");
    for (const v of src.keys()) {
      const elsewhere = moved.some((m) => m.from[0] === ci + 1 && v >= m.from[1] && v <= m.from[2]);
      if (v > count && !elsewhere) throw new Error(`${book.id} ${ci + 1}:${v} is beyond the KJV's ${count} verses`);
    }
    return out;
  });
  for (const m of moved) {
    const [fc, first, last] = m.from;
    for (let k = 0; k <= last - first; k++) {
      const text = source.get(fc)!.get(first + k);
      if (!text) throw new Error(`${book.id} ${fc}:${first + k} expected to be moved`);
      const [tc, tv] = m.to;
      if (chapters[tc - 1][tv - 1 + k]) throw new Error(`${book.id} ${tc}:${tv + k} already has text`);
      chapters[tc - 1][tv - 1 + k] = text;
    }
  }
  chapters.forEach((c, ci) =>
    c.forEach((text, vi) => {
      if (text) verses++;
      else omitted.push(`${book.id} ${ci + 1}:${vi + 1}`);
    }),
  );
  writeFileSync(join(outDir, `${book.id}.json`), JSON.stringify(chapters));
});
const loaders = BOOKS.map((b) => `  ${JSON.stringify(b.id)}: () => import("./${b.id}.json"),`).join("\n");
writeFileSync(
  join(outDir, "index.ts"),
  `// GENERATED by scripts/generate-english.ts. Do not edit.\n` +
    `type Chapters = string[][];\n` +
    `export const ${id}_BOOKS: Record<string, () => Promise<{ default: Chapters }>> = {\n${loaders}\n};\n`,
);
console.log(`${id}: wrote ${BOOKS.length} books, ${verses} verses to ${outDir}`);
console.log(`Left out (empty, skipped when shown): ${omitted.join(", ") || "none"}`);
